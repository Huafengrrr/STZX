function para(text, opts) {
  opts = opts || {};
  return new Paragraph({
    spacing: { after: 120 },
    alignment: opts.align || AlignmentType.LEFT,
    indent: opts.indent ? { left: 360 } : undefined,
    children: [new TextRun({ text: text, size: 22, font: "Microsoft YaHei" })],
  });
}

// Q&A block generator
function qaBlock(q, answerLines) {
  var items = [];
  items.push(new Paragraph({
    spacing: { before: 200, after: 100 },
    shading: { fill: "F0F4FA", type: ShadingType.CLEAR },
    children: [new TextRun({ text: q, bold: true, size: 23, font: "Microsoft YaHei", color: "C45911" })],
  }));
  for (var j = 0; j < answerLines.length; j++) {
    var line = answerLines[j];
    var isDash = line.indexOf("- ") === 0;
    items.push(new Paragraph({
      spacing: { after: isDash ? 60 : 80 },
      indent: isDash ? { left: 480 } : undefined,
      children: [new TextRun({ text: line, size: 21, font: "Microsoft YaHei" })],
    }));
  }
  return items;
}

// Table helper
function makeHeaderRow(col1, col2, w1, w2) {
  var tc = function(txt, w) {
    return new TableCell({
      borders: borders, width: { size: w, type: WidthType.DXA },
      shading: { fill: "2E75B6", type: ShadingType.CLEAR },
      margins: { top: 80, bottom: 80, left: 120, right: 120 },
      children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ text: txt, bold: true, size: 22, font: "Microsoft YaHei", color: "FFFFFF" })] })]
    });
  };
  return new TableRow({ children: [tc(col1, w1), tc(col2, w2)] });
}

function makeDataRow(a, b, w1, w2, idx) {
  var tc = function(txt, w, bold) {
    return new TableCell({
      borders: borders, width: { size: w, type: WidthType.DXA },
      shading: idx % 2 === 0 ? { fill: "F5F8FC", type: ShadingType.CLEAR } : undefined,
      margins: { top: 60, bottom: 60, left: 120, right: 120 },
      children: [new Paragraph({ children: [new TextRun({ text: txt, bold: bold, size: 21, font: "Microsoft YaHei" })] })]
    });
  };
  return new TableRow({ children: [tc(a, w1, true), tc(b, w2, false)] });
}

